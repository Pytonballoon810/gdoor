"""Export the gdoor-din board as an OpenSCAD include (board_ghost.scad).

Run with KiCad's python, from hardware/boards/din:
    "C:/Program Files/KiCad/10.0/bin/python.exe" enclosure/board_export.py

Each part becomes a box (its fab-layer body outline, at an estimated body
height) and each through-hole pad a pin stub on the back side, in
enclosure.scad's design frame: X = depth (0 = DIN mounting face, board front
edge at +X), Y = height (board top edge up), Z = width (board back side
towards Z = 0, component side towards +Z, where enclosure.scad draws it).

X and Y below, with the component side at +Z, are a reflection of the board,
not a rotation: the design frame holds the board's mirror image.
enclosure.scad mirrors every output about z = W/2 (its real() module), which
turns this back into the real board, with the component side towards the
lid at Z = 0. Do not "fix" one side of this without the other.
The enclosure uses the result for the fit check only; the walls are not
derived from it.
"""
import os
import pcbnew

HERE = os.path.dirname(os.path.abspath(__file__))
PCB = os.path.join(HERE, "..", "esp32.kicad_pcb")

# Must match enclosure.scad: board front edge X, board top edge Y.
BOARD_FRONT_X = 52.4
BOARD_TOP_Y = 87.5
FRONT_FACE_X = 60.6   # outside of the window face (enclosure.scad front_x)

# Body height above the board per footprint name fragment (mm, rounded up).
HEIGHTS = [
    ("RJ45", 13.5), ("USB_C", 3.3), ("anschlussklemme", 10.5),
    ("PinHeader", 11.0), ("ESP32-S3-WROOM", 3.2), ("SOT-223", 1.8),
    ("D_SMA", 2.4), ("SW_SPST", 1.6), ("SOIC", 1.8), ("LQFP", 1.6),
    ("C_1210", 2.6), ("C_1206", 1.8), ("Choke", 12.0),
]
DEFAULT_H = 1.2
PIN_STUB = 3.0   # THT lead length below the board, untrimmed


def mm(v):
    return pcbnew.ToMM(v)


def X(kx):
    return BOARD_FRONT_X - (kx - 100.0)


def Y(ky):
    return BOARD_TOP_Y - (ky - 60.0)


def body_bbox(f, crtyd):
    """Body outline from the fab layer; courtyard, then footprint box, as
    fallbacks. The fab outline leaves out keepouts (the module antenna)."""
    fab = pcbnew.F_Fab if f.GetLayerName() == "F.Cu" else pcbnew.B_Fab
    bb = None
    for g in f.GraphicalItems():
        if g.GetLayer() == fab and g.GetClass() != "PCB_TEXT":
            if bb is None:
                bb = g.GetBoundingBox()
            else:
                bb.Merge(g.GetBoundingBox())
    if bb is not None and bb.GetWidth() > 0 and bb.GetHeight() > 0:
        return bb
    if crtyd.OutlineCount():
        return crtyd.BBox()
    return f.GetBoundingBox(False)  # custom footprints (J1, J4)


def main():
    b = pcbnew.LoadBoard(PCB)
    out = ["// generated by board_export.py from esp32.kicad_pcb, do not edit",
           "// [ref, side(1=F,-1=B), x0, x1, y0, y1, height, dnp]",
           "board_parts = ["]
    pins = []
    for f in b.GetFootprints():
        front = f.GetLayerName() == "F.Cu"
        c = f.GetCourtyard(pcbnew.F_CrtYd if front else pcbnew.B_CrtYd)
        bb = body_bbox(f, c)
        fp = f.GetFPIDAsString()
        if "Logo" in fp:
            continue
        h = next((v for k, v in HEIGHTS if k in fp), DEFAULT_H)
        x0, x1 = X(mm(bb.GetRight())), X(mm(bb.GetX()))
        y0, y1 = Y(mm(bb.GetBottom())), Y(mm(bb.GetY()))
        # Clip parts to the board outline; at the front, to the window face,
        # because the RJ45 and USB-C sit on the front tab and overhang it.
        x0, x1 = max(x0, BOARD_FRONT_X - 50), min(x1, FRONT_FACE_X)
        y0, y1 = max(y0, BOARD_TOP_Y - 85), min(y1, BOARD_TOP_Y)
        out.append(f'  ["{f.GetReference()}", {1 if front else -1}, '
                   f"{x0:.2f}, {x1:.2f}, {y0:.2f}, {y1:.2f}, {h}, "
                   f"{'true' if f.IsDNP() else 'false'}],")
        for p in f.Pads():
            if p.GetAttribute() == pcbnew.PAD_ATTRIB_PTH and not f.IsDNP():
                pos = p.GetPosition()
                pins.append(f"  [{X(mm(pos.x)):.2f}, {Y(mm(pos.y)):.2f}],")
    out.append("];")
    out.append(f"board_pin_stub = {PIN_STUB};")
    out.append("board_pins = [")
    out += pins
    out.append("];")
    with open(os.path.join(HERE, "board_ghost.scad"), "w", newline="\n") as fh:
        fh.write("\n".join(out) + "\n")


main()
